test('long-running read-only submit immediately warns against refresh', async ({ page }) => {
  await signIn(page, 'user4.test')
  await expect(page.getByRole('heading', { name: 'Reconnect before checking Discover' })).toBeVisible()
  await expect(page.locator('form[action="/reconnect"]')).toContainText('Reconnect with Discover access')
  await page.locator('form[action="/diagnostics/yield"]').evaluate(form => {
    form.addEventListener('submit', event => event.preventDefault(), { once: true })
  })
  await page.getByRole('button', { name: 'Measure feed coverage' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Starting a fresh measurement' })).toBeVisible()
  await expect(page.getByText('You can return to the dashboard while the read-only check continues.')).toBeVisible()
  await expect(page.locator('body')).toHaveAttribute('aria-busy', 'true')
  await page.reload()
  await page.getByRole('button', { name: 'Reconnect with Discover access' }).click()
  await expect(page.getByRole('heading', { name: 'Your feed policies' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Reconnect before checking Discover' })).toHaveCount(0)
})

