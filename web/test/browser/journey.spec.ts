import { expect, test, type Page } from '@playwright/test'
import { policy } from '../fixtures.js'

async function signIn(page: Page, handle: string) {
  await page.goto('/')
  await page.getByLabel('Handle').fill(handle)
  await page.getByRole('button', { name: 'Continue securely' }).click()
  await expect(page.getByRole('heading', { name: 'Your feed policies' })).toBeVisible()
  await expect(page.getByText(`@${handle}`, { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Measure feed coverage' })).toBeVisible()
}

test('landing publishes a fetchable large social preview', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('meta[property="og:title"]')).toHaveAttribute('content', 'atproto-acl · Personal feed policy')
  await expect(page.locator('meta[property="og:image"]')).toHaveAttribute('content', 'https://atproto-acl.neutral.zone/social-card.png')
  await expect(page.locator('meta[name="twitter:card"]')).toHaveAttribute('content', 'summary_large_image')
  const image = await page.request.get('/social-card.png')
  expect(image.status()).toBe(200)
  expect(image.headers()['content-type']).toBe('image/png')
  expect((await image.body()).byteLength).toBeGreaterThan(100_000)
  await page.getByRole('link', { name: 'Help' }).click()
  await expect(page.getByRole('heading', { name: 'How previews and changes work' })).toBeVisible()
  await expect(page.getByText('A maximum limits that source; it does not invent more accounts.')).toBeVisible()
})

