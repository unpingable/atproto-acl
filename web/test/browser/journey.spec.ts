test('desktop preview, exact approval, durable execution, and user isolation', async ({ browser }) => {
  const first = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const page = await first.newPage()
  await signIn(page, 'user1.test')
  const refused = await page.request.post('/overrides', {
    headers: { Origin: 'https://attacker.invalid', 'Content-Type': 'application/x-www-form-urlencoded' },
    data: 'subject=did%3Aplc%3Aalice&kind=exempt&enabled=1',
  })
  expect(refused.status()).toBe(403)
  await page.getByRole('link', { name: 'Configure Poasters Quarantine' }).click()
  await page.getByLabel('Policy name').fill('Attention test')
  await expect(page.getByLabel('Account source')).toHaveValue('feeds')
  await expect(page.getByText('Check up to 500 accounts appearing in your Timeline and Discover feeds')).toBeVisible()
  await expect(page.getByLabel('Policy YAML')).not.toBeVisible()
  await page.getByRole('button', { name: 'Save policy' }).click()
  const policyUrl = page.url()
  await page.getByRole('button', { name: 'Build preview' }).click()
  const previewUrl = page.url()
  await expect(page.getByRole('heading', { name: 'Checked 3 accounts from @user1.test’s Timeline and Discover feeds' })).toBeVisible()
  await expect(page.getByText('1 new mute proposed. 1 followed account needs separate review.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Proposed changes 1' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Followed review 1' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'No change 1' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Unresolved 0' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Alice' })).toBeVisible()
  await expect(page.getByText('@alice.example')).toBeVisible()
  const followed = page.locator('.followed-review')
  await expect(followed).not.toBeVisible()
  await page.getByRole('button', { name: 'Followed review 1' }).click()
  await expect(followed).toBeVisible()
  await expect(followed).not.toHaveAttribute('open', '')
  await expect(followed.getByText('Review these separately')).not.toBeVisible()
  await followed.getByText('Followed accounts that matched').click()
  await expect(followed.getByText('Review these separately')).toBeVisible()
  await expect(followed.getByLabel('Select did:plc:bob')).not.toBeChecked()
  await expect(followed.getByRole('button', { name: 'Approve selected followed-account mutes' })).toHaveAttribute('value', 'apply_followed')
  await page.getByRole('button', { name: 'No change 1' }).click()
  await expect(page.getByText('No matching evidence found', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Proposed changes 1' }).click()
  if (process.env.ATPROTO_ACL_SCREENSHOT_DIR) {
    await page.screenshot({ path: process.env.ATPROTO_ACL_SCREENSHOT_DIR + '/desktop-preview.png', fullPage: true })
  }
  await page.getByLabel('Select did:plc:alice').check()
  await page.getByRole('button', { name: 'Approve selected mutes' }).click()
  await expect(page.getByRole('heading', { name: /Applying 1 change|1 account muted/ })).toBeVisible()
  const jobUrl = page.url()
  await expect.poll(async () => {
    await page.reload()
    return (await page.locator('.title .status').textContent())?.trim()
  }).toBe('completed')
  await expect(page.getByText('Muted', { exact: true })).toBeVisible()
  if (process.env.ATPROTO_ACL_SCREENSHOT_DIR) {
    await page.screenshot({ path: process.env.ATPROTO_ACL_SCREENSHOT_DIR + '/action-results.png', fullPage: true })
  }
  await expect(page.getByRole('progressbar')).toHaveAttribute('value', '1')
  await expect(page.getByText('Add private mute')).toBeVisible()
  await expect(page.getByRole('link', { name: 'View profile' })).toHaveAttribute('href', 'https://bsky.app/profile/did:plc:alice')
  await page.getByText('Seen 2 times · view sampled posts').click()
  await expect(page.getByRole('link', { name: /View sampled post/ }).first()).toHaveAttribute('target', '_blank')
  await expect(page.getByText('did:plc:alice')).not.toBeVisible()
  await page.getByText('Technical details', { exact: true }).click()
  await expect(page.getByText('did:plc:alice')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Muted', { exact: true })).toBeVisible()
  await page.goto('/app')
  await expect(page.getByRole('heading', { name: 'Your feed policies' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Preview accounts' }).first()).toBeVisible()
  await expect(page.getByText(/Last preview proposed|proposed change/).first()).toBeVisible()
  if (process.env.ATPROTO_ACL_SCREENSHOT_DIR) {
    await page.screenshot({ path: process.env.ATPROTO_ACL_SCREENSHOT_DIR + '/dashboard.png', fullPage: true })
  }

  const second = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const mobile = await second.newPage()
  await signIn(mobile, 'user2.test')
  for (const privateUrl of [policyUrl, previewUrl, jobUrl]) {
    const response = await mobile.goto(privateUrl)
    expect(response?.status()).toBe(404)
    await expect(mobile.getByRole('heading', { name: 'Page not found' })).toBeVisible()
    await expect(mobile.locator('body')).not.toContainText('did:plc:alice')
  }
  await second.close()
  await first.close()
})

